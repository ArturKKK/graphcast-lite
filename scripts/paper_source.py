#!/usr/bin/env python3
"""Предобработка исходника рукописи — в одном месте на обе сборки.

Собирают рукопись два разных скрипта: `paper_to_html.py` (простая вёрстка для
вычитки) и `paper_artifact.py` (вёрстка с формулами, из неё печатается PDF).
Правки, внесённые в один, до 30.08.2026 не попадали во второй — и та самая
сборка, которая идёт в журнал, оставалась с надстрочными знаками в виде крышек
и с приложенным промптом для рецензирующей нейросети.

Поэтому всё, что относится к самому тексту, живёт здесь и зовётся обоими.
"""
from __future__ import annotations

import re

# Разделы, которые не входят в рукопись ни при каких обстоятельствах.
# Отсечение безусловное: рассчитывать на флаг нельзя, забудут — и служебный
# текст уедет в журнал.
SERVICE_SECTIONS = (
    "## Промпт для независимой проверки",
    "## Перечень рисунков",
)

# Надстрочные знаки аффиляций: Табаков^1,2^ -> Табаков<sup>1,2</sup>.
# Шаблон нарочно узкий — только цифры и запятые. Формулы вида ^{(r)}, ^{2},
# ^{\mathsf{T}} начинаются с фигурной скобки и под него не подпадают; широкий
# шаблон испортил бы всю математику статьи молча.
_SUP = re.compile(r"\^(\d+(?:,\d+)*)\^")


def cut_service_sections(text: str) -> tuple[str, list[str]]:
    """Отрезать служебные разделы. Возвращает текст и список отрезанного."""
    cut = []
    for marker in SERVICE_SECTIONS:
        if marker in text:
            text = text.split(marker)[0]
            cut.append(marker)
    return text, cut


def superscripts(text: str) -> tuple[str, int]:
    """Крышки аффиляций -> теги. Возвращает текст и число замен."""
    return _SUP.subn(r"<sup>\1</sup>", text)


def prepare(text: str) -> tuple[str, dict]:
    """Полная предобработка исходника. Второй элемент — что было сделано."""
    text, cut = cut_service_sections(text)
    text, n_sup = superscripts(text)
    return text, {"cut": cut, "superscripts": n_sup}
