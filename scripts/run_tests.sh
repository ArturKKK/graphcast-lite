#!/usr/bin/env bash
# Тесты постобработки. Одна короткая команда — их и надо набирать на виртуалке.
#
# Работают и без torch: датасет и геометрия от него не зависят, а в conftest.py
# стоит заглушка на случай, когда его нет (например, при проверке на ноутбуке).
#
# Запуск: bash scripts/run_tests.sh [дополнительные аргументы pytest]
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1
python3 -m pytest tests/ -q "$@"
