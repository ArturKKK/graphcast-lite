"""Геометрия узлов сетки: соседи станции и проверка порядка узлов.

Вынесено из scripts/postproc/build_corpus.py. Там эти вычисления сидели внутри
сборщика, который тянет за собой torch и всю модель, и проверить их было можно
только запустив двухчасовой счёт. Здесь один numpy, поэтому они покрыты тестами.
"""
from __future__ import annotations

import numpy as np


def neighbour_indices(node_lats: np.ndarray, node_lons: np.ndarray,
                      lat: float, lon: float, k: int) -> list[int]:
    """Номера k ближайших к точке узлов.

    Долгота сжимается на косинус широты. Без этого на 55° с.ш. градус долготы
    вдвое короче градуса широты, и «ближайшими» оказывается полоса, вытянутая
    по долготе, а не окружение точки: на сетке 0,25° это давало набор радиусом
    до 34,6 км вместо 28,8.

    Долгота ожидается в той же системе, что и у узлов (у нас 0..360).
    """
    if k <= 0:
        return []
    kx = np.cos(np.radians(lat)) ** 2
    d2 = (node_lats - lat) ** 2 + kx * (node_lons - lon) ** 2
    return np.argsort(d2)[:k].astype(int).tolist()


def field_coherence(node_lats: np.ndarray, node_lons: np.ndarray,
                    values: np.ndarray, mask: np.ndarray | None = None,
                    k: int = 6) -> float:
    """Связь значения в узле со средним по его соседям.

    Метеорологическое поле гладкое: у настоящего кадра значение в узле почти
    совпадает со средним по соседям, у перемешанного связь пропадает. Это и есть
    проверка того, что значения легли на свои узлы.

    ``mask`` позволяет считать связь по части сетки. Это существенно: вставка
    занимает 1,9 % узлов, и её порча в общей связи не видна вовсе — при
    перемешанной вставке связь по всей сетке остаётся 1,000.

    Возвращает NaN, если узлов слишком мало или поле постоянно: на двух десятках
    точек коэффициент связи скачет как угодно, и решать по нему нельзя.

    Чего проверка не ловит: гладкую полосу значений, легшую из другого места
    сетки, — поле остаётся гладким, связь держится около 0,8. Судит она о
    гладкости, а не о правильности значений. Настоящие пути так не ломаются:
    значения раскладываются двумя присваиваниями по маске, и сбой там даёт
    разнобой, а не аккуратный сдвиг. См. tests/postproc/test_geometry.py.
    """
    from scipy.spatial import cKDTree

    phi, lam = np.radians(node_lats), np.radians(node_lons)
    xyz = np.c_[np.cos(phi) * np.cos(lam), np.cos(phi) * np.sin(lam), np.sin(phi)]
    _, nb = cKDTree(xyz).query(xyz, k=k)
    f = np.asarray(values, dtype=np.float64)
    nbm = f[nb[:, 1:]].mean(1)

    sel = slice(None) if mask is None else mask
    a, b = f[sel], nbm[sel]
    if a.size < 100 or a.std() < 1e-9 or b.std() < 1e-9:
        return float("nan")
    return float(np.corrcoef(a, b)[0, 1])


# Пороги проверки. По всей сетке связь у настоящего кадра 0,999, у перемешанного
# 0,003; во вставке 0,993 и -0,015. Пороги стоят посередине с большим запасом:
# ловить надо не мелкое расхождение, а разъехавшийся порядок.
COHERENCE_MIN_WHOLE = 0.85
COHERENCE_MIN_REGIONAL = 0.60
